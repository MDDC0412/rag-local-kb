/**
 * RAG 术语词典与面试题。
 *
 * 为什么单独放一个内容文件：
 * 1. 内容有几百条，塞进 .vue 会把组件代码淹掉；
 * 2. 术语和面试题是**同一套知识**的两种切法（一个按词条、一个按问题），
 *    放一起才能互相引用（术语指向相关面试题，反之亦然）。
 *
 * 写作原则：
 * - 每个术语都要回答「是什么 / 为什么需要 / 本项目怎么用的」，只讲定义等于没讲；
 * - 面试题的答案要有**取舍**，只说"用什么"不说"为什么不用别的"就是背书；
 * - 提到本项目实现时给出具体文件，读者能直接跳过去看代码。
 */

export interface Term {
  /** 词条名，英文缩写放括号里便于搜索 */
  name: string
  /** 一句话定义，扫读用 */
  brief: string
  /** 展开解释：为什么需要它、它解决什么问题 */
  detail: string
  /** 本项目的实际用法（可选） */
  project?: string
  /** 常见误解或面试考点（可选） */
  pitfall?: string
  /** 相关词条，用于跳转 */
  related?: string[]
}

export interface TermGroup {
  key: string
  title: string
  /** 这一组讲的是链路上的哪一段 */
  summary: string
  terms: Term[]
}

