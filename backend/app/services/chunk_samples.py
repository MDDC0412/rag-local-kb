"""分块策略的示例文档：每种策略配一份"正好适合它"的文档。

用途：用户在预览页点「看样例」，直接看到这种排版格式 + 真实切分结果，
一眼明白"这种策略适合什么样的文档"。

设计原则
--------
- 每份样例都要真的能体现该策略的优势（例如 sentence 的样例必须是多条款文档，
  条款被切断就会出问题；markdown 的样例必须有层级标题）；
- 样例是内置常量，不落库、不进入用户的向量库；
- 切分结果是运行时用真实 split_local 算出来的，不是手写的假数据。
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(slots=True)
class StrategySample:
    """一份策略样例。"""

    strategy: str
    title: str
    # 这份文档"长什么样"，一句话说明为什么适合该策略
    why: str
    # 排版特征要点，前端用列表展示
    traits: list[str] = field(default_factory=list)
    # 完全模拟真实文档的排版
    document: str = ""


